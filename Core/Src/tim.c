/// @brief Reads pwm inputs
/// @param htim Pointer to the timer
/// @param ch_period  Channel input for the period of the signal
/// @param ch_high Channel input for how long the signal was high for
/// @return The PWM output of a sensor
static PWM PWM_Read(TIM_HandleTypeDef *htim, uint32_t ch_period, uint32_t ch_high){
  PWM ret;
  uint32_t period;
  uint32_t high;

  period = HAL_TIM_ReadCapturedValue(htim,ch_period) + 1;
  high = HAL_TIM_ReadCapturedValue(htim,ch_high) + 1;

  if (period > 1) {
      uint32_t psc;
      psc = htim->Instance->PSC + 1;
      ret.freq  = (float)TIM_CLK_HZ / (psc * period);
      ret.duty = 100.0f * high / period;
    }
    return ret;
}

/// @brief Reduces the output power from taking inputs from each wheel speed sensor
/// to see if the rear wheels are slipping 
/// @return percentage to reduce the power by
float Traction_Control(){
  float speed[4] = {0};
  float vech_speed;
  float avg_slip;
  float power_red;

  for(uint8_t i = 0; i < 4; i++){
     if (HAL_GetTick() - ws[i].last_ms >= WS_TIMEOUT_MS || ws[i].period == 0){
        speed[i] = 0.0f;
      }                                    // no tooth in 500 ms, so stopped
    speed[i] = TIM_TICK_HZ * 60.0f / ((float)ws[i].period * WS_TEETH);
  }
  vech_speed = (speed[0] + speed[1]) / 2;
  avg_slip = (((speed[2] - vech_speed) / vech_speed) + ((speed[3] - vech_speed) / vech_speed)) / 2;
  //sees if there is over 15% slip on the rear wheels on average 
  if(avg_slip >= .15){
    power_red = 0.0f;
  }
  else{
    power_red = avg_slip * .95;
  }

  return power_red;
}

void HAL_TIM_IC_CaptureCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance != TIM4) return;
    for (int i = 0; i < 4; i++) {
        WheelSpeed *w = &ws[i];
        if (htim->Channel != w->active) continue;

        uint16_t cap = HAL_TIM_ReadCapturedValue(htim, w->channel);
        uint32_t now = HAL_GetTick();
        if (now - w->last_ms < WS_TIMEOUT_MS)
            w->period = (uint16_t)(cap - w->last_cap);  // 16-bit math handles the wrap automatically
        w->last_cap = cap;
        w->last_ms  = now;
    }
}
